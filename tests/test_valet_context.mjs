import assert from 'node:assert/strict';
import {validateContext,bookPrompt} from '../tools/openclaw/valet-context.mjs';
import {createPassportConnection} from '../tools/openclaw/passport-proxy.mjs';
const id='a'.repeat(64),book='b'.repeat(32),key=`agent:passport:passport-${id}-book-${book}`;
const context={bookId:book,title:'三国演义',chapter:'第一回',page:2,text:'宴桃园',truncated:false};
assert.equal(validateContext(id,{sessionKey:key,context}).sessionKey,key);
assert.throws(()=>validateContext('foreign',{sessionKey:key,context}));
assert.throws(()=>validateContext(id,{sessionKey:key,context:{...context,page:true}}));
assert.throws(()=>validateContext(id,{sessionKey:key,context:{...context,text:'汉'.repeat(4001)}}));
const upstream=[],downstream=[];let failed='';
const c=createPassportConnection({sendUpstream:f=>upstream.push(f),sendClient:f=>downstream.push(f),close:x=>failed=x});
c.upstream({type:'event',event:'connect.challenge'});
c.client({type:'req',id:'connect',method:'connect',params:{client:{deviceFamily:'e-ink4-plus'},device:{id,signature:'proof',publicKey:'public'},auth:{deviceToken:'token'},role:'operator',caps:['passport-ima-v1','valet-book-context-v1']}});
c.upstream({type:'res',id:'connect',ok:true,payload:{policy:{maxPayload:660000}}});
assert.equal(downstream.at(-1).payload.valetBookContext,1);
c.client({type:'req',id:'context',method:'valet.context.set',params:{sessionKey:key,context}});
assert.equal(downstream.at(-1).ok,true);
c.client({type:'req',id:'ask',method:'chat.send',params:{sessionKey:key,message:'问题',attachments:[{type:'audio',content:'wav'}]}});
assert.equal(upstream.at(-1).params.message,bookPrompt(context)+'问题');
c.client({type:'req',id:'foreign',method:'chat.history',params:{sessionKey:`agent:passport:passport-${'f'.repeat(64)}`}});
assert.equal(downstream.at(-1).ok,false);
c.client({type:'req',id:'clear',method:'valet.context.set',params:{sessionKey:`agent:passport:passport-${id}`,context:null}});
c.client({type:'req',id:'solo',method:'chat.send',params:{sessionKey:`agent:passport:passport-${id}`,message:'天气'}});
assert.equal(upstream.at(-1).params.message,'天气');assert.equal(failed,'');c.stop('done');
console.log('Valet book contexts: negotiation, ownership, UTF8 limits, audio prompt, standalone clearing PASS');
